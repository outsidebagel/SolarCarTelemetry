// Map should be locked on car
var lockedMapOnCar = true;

L.tileLayer('https://tile.openstreetmap.org/{z}/{x}/{y}.png', {
    maxZoom: 19,
    attribution: '&copy; <a href="http://www.openstreetmap.org/copyright">OpenStreetMap</a>'
}).addTo(map);

// Updates the marker and centering of map given new gps coords
export function updateMap(curLatitude, curLongitude) {
    if (lockedMapOnCar){
        // Move car marker to new lat and long on map
        myIcon.setLatLng([curLatitude, curLongitude]);
    
        // Re-center map on moved marker if map locked
        map.panTo([curLatitude, curLongitude])
    }
}

// Adds features to the route segment
function onEachFeature(feature, layer) {
    // does this feature have a property named popupContent?
    if (feature.properties && feature.properties.description) {
        // Name + Description
        layer.bindPopup(
            feature.properties.name + "<br><br>" + feature.properties.description);   
    }
}

// Adds styles to the route segment
function routeStyle(feature) {
    return {
        "color": feature.properties.color,
        "weight": 5,
        "opacity": 0.65
    };
}


// Render the route
for (let i = 0; i < routeParts.length; i++) {
    L.geoJSON(routeParts[i], {
        onEachFeature: onEachFeature,
        style: routeStyle
    }).addTo(map);
}


